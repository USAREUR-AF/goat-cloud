def parse_expires_at(value):
    """Return the moment an expiry value names, as a UTC datetime, or None.

    Reads the contract's forms and also a date alone or a timestamp without a
    zone, both taken as UTC, so that a value in the wrong form still expires.
    Whether the value has the required form is a separate question: ask
    expires_at_is_valid and report a value that fails it.
    """
    if not isinstance(value, str) or not value.strip():
        return None
    text = value.strip()
    compact = _COMPACT_UTC_RE.match(text)
    try:
        if compact:
            return datetime(*(int(part) for part in compact.groups()), tzinfo=UTC)
        moment = datetime.fromisoformat(text.replace("Z", "+00:00"))
    except ValueError:
        return None
    if moment.tzinfo is None:
        return moment.replace(tzinfo=UTC)
    return moment.astimezone(UTC)


