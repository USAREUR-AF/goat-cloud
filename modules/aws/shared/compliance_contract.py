def normalize_repository(value):
    """Return a repository value in the contract's canonical form.

    https scheme, lowercase host, no user name, no trailing ".git" and no
    trailing slash. "git@host:org/repo.git", "ssh://git@host/org/repo.git" and
    "https://Host/org/repo/" all become "https://host/org/repo". Compare a tag
    value with a registry entry only after normalizing both. A value that is
    not a repository address is returned stripped and otherwise unchanged.
    """
    text = (value or "").strip()
    if not text:
        return ""
    url = _URL_RE.match(text)
    if url:
        scheme, host, path = url.group(1).lower(), url.group(2), url.group(3) or ""
        if scheme not in ("http", "https"):
            host = host.split(":", 1)[0]
    else:
        scp = _SCP_RE.match(text)
        if not scp:
            return text
        host, path = scp.group(1), scp.group(2)
    path = path.strip("/")
    if path.endswith(".git"):
        path = path[: -len(".git")].rstrip("/")
    return f"https://{host.lower()}/{path}" if path else f"https://{host.lower()}"


def same_repository(left, right):
    """True when two repository values name the same repository."""
    return bool(left) and bool(right) and normalize_repository(left) == normalize_repository(right)
