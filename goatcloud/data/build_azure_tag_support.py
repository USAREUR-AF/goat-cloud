"""Writes azure_tag_support.yaml from Microsoft's tag-support article.

    curl -sLO https://raw.githubusercontent.com/MicrosoftDocs/azure-docs/main/articles/azure-resource-manager/management/tag-support.md
    python goatcloud/data/build_azure_tag_support.py tag-support.md

The article has one table per resource provider with the columns
"Resource type | Supports tags | Tag in cost report".
"""

import re
import sys
from pathlib import Path

ROW = re.compile(r"^>\s*\|\s*([^|]+?)\s*\|\s*(Yes|No)\s*\|", re.IGNORECASE)


def parse(text):
    provider, date, supported, unsupported = None, None, set(), set()
    for line in text.splitlines():
        if line.startswith("ms.date:"):
            date = line.split(":", 1)[1].strip()
        elif line.startswith("## "):
            provider = line[3:].strip().lower()
        elif provider and (match := ROW.match(line)):
            name = re.sub(r"\s*/\s*", "/", match.group(1)).lower()
            if name == "resource type":
                continue
            (supported if match.group(2).lower() == "yes" else unsupported).add(f"{provider}/{name}")
    return date, sorted(supported - unsupported), sorted(unsupported)


def main(path):
    date, supported, unsupported = parse(Path(path).read_text(encoding="utf-8-sig"))
    lines = [
        "# Azure resource types and whether each has a tags property.",
        "#",
        "# Generated by build_azure_tag_support.py from Microsoft's article",
        "# https://learn.microsoft.com/azure/azure-resource-manager/management/tag-support",
        f"# (article date {date}). Do not edit; run the script again.",
        "#",
        "# A type in neither list is not classified: the scan reports it as",
        "# not evaluated and never grades it.",
        "",
        'schema_version: "1.0"',
        f'source_date: "{date}"',
        "",
        "# Types Microsoft lists with a row and no tags property in the same table",
        "# are in cannot_carry_tags only.",
        "can_carry_tags:",
        *[f"  - {name}" for name in supported],
        "",
        "cannot_carry_tags:",
        *[f"  - {name}" for name in unsupported],
        "",
        "# Classified by hand, not in the article. Each line states why.",
        "unverified:",
        "  # Resource groups carry tags; the article lists Microsoft.Resources/resourceGroups",
        "  # and Resource Graph names the type subscriptions/resourcegroups.",
        "  microsoft.resources/subscriptions/resourcegroups: can_carry_tags",
        "",
    ]
    out = Path(__file__).with_name("azure_tag_support.yaml")
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(supported)} can carry tags, {len(unsupported)} cannot -> {out}")


if __name__ == "__main__":
    main(sys.argv[1])
